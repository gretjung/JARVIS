# ============================================================
# JARVIS SYSTEM SKILL v2.0
# ============================================================

from core.identity import (
    JARVIS_NAME,
    JARVIS_VERSION,
    get_response,
)


class SystemSkill:

    name = "SYSTEM"

    enabled = True

    # ========================================================
    # CAN HANDLE
    # ========================================================

    def can_handle(self, text):

        if not self.enabled:
            return False

        lower = text.lower().strip()

        commands = (
            "ทดสอบ skill",
            "ทดสอบระบบ skill",
            "skill status",

            "สถานะระบบ",
            "เช็คสถานะระบบ",
            "เช็กสถานะระบบ",
            "system status",

            "เวอร์ชัน",
            "เวอร์ชั่น",
            "version",

            "คุณคือใคร",
            "นายคือใคร",
            "who are you",

            "สวัสดี",
            "หวัดดี",
            "hello",
            "hi",
            "hey jarvis",
        )

        return lower in commands

    # ========================================================
    # EXECUTE
    # ========================================================

    def execute(self, text):

        lower = text.lower().strip()

        # ----------------------------------------------------
        # SKILL TEST
        # ----------------------------------------------------

        if lower in (
            "ทดสอบ skill",
            "ทดสอบระบบ skill",
        ):

            return (
                "ระบบ Skill ทำงานปกติครับ"
            )

        # ----------------------------------------------------
        # SKILL STATUS
        # ----------------------------------------------------

        if lower == "skill status":

            return (
                "Skill Registry ออนไลน์ครับ"
            )

        # ----------------------------------------------------
        # SYSTEM STATUS
        # ----------------------------------------------------

        if lower in (
            "สถานะระบบ",
            "เช็คสถานะระบบ",
            "เช็กสถานะระบบ",
            "system status",
        ):

            return (
                "ระบบหลักของ JARVIS ออนไลน์ครับ"
            )

        # ----------------------------------------------------
        # VERSION
        # ----------------------------------------------------

        if lower in (
            "เวอร์ชัน",
            "เวอร์ชั่น",
            "version",
        ):

            return (
                f"{JARVIS_NAME} "
                f"Version {JARVIS_VERSION} "
                "ครับ"
            )

        # ----------------------------------------------------
        # IDENTITY
        # ----------------------------------------------------

        if lower in (
            "คุณคือใคร",
            "นายคือใคร",
            "who are you",
        ):

            return (
                "ผมคือ JARVIS "
                "ผู้ช่วยปัญญาประดิษฐ์ส่วนตัวของคุณครับ"
            )

        # ----------------------------------------------------
        # GREETING
        # ----------------------------------------------------

        if lower in (
            "สวัสดี",
            "หวัดดี",
            "hello",
            "hi",
            "hey jarvis",
        ):

            return get_response(
                "greeting"
            )

        return None